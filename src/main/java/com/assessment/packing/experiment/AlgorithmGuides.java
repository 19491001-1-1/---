    private static Guide shelf(AlgorithmId id) {
        String key = id == AlgorithmId.SHELF ? "NF" : id.name().split("_")[1];
        boolean global = id.name().endsWith("_GLOBAL");
        boolean wm = id.name().endsWith("_WM");
        String rule = switch (key) {
            case "NF" -> "NF（Next-Fit，下一适配）只检查最新一层，旧层即使还剩宽度也不再用普通选层流程回填。";
            case "FF" -> "FF（First-Fit，首次适配）从最早的层开始检查，找到第一个宽高允许放入的层就采用，不继续比较后面的层。";
            case "BWF" -> "BWF（Best Width Fit，最佳宽度匹配）比较放入后剩余宽度，优先选择剩余最少的可行层，让层尾更贴合。";
            case "BHF" -> "BHF（Best Height Fit，最佳高度匹配）比较层高与当前方向零件高度的非负差值，优先选高度差较小的可行层。";
            case "BAF" -> "BAF（Best Area Fit，最佳面积匹配）在本实现中比较放置前的层尾矩形面积，即剩余宽度乘当前层高，优先选面积较小的可行层。它不计算所有内部空洞的总面积。";
            case "WWF" -> "WWF（Worst Width Fit，最宽余量匹配）通常选择放入后剩余宽度最大的可行层；本实现对剩余宽度恰好为零的完全匹配候选优先处理。";
            default -> throw new IllegalArgumentException(key);
        };
        String example = switch (key) {
            case "NF" -> "旧层还能放一个小件，但最新层放不下，普通 NF 会尝试新开层，而不会因为旧层有空间就回去。";
            case "FF" -> "第一层、第三层都能放当前件，FF 采用第一层，即使第三层可能更贴合。";
            case "BWF" -> "两个可行层放入后分别剩宽 2 和 7，BWF 选择剩 2 的层。";
            case "BHF" -> "一个高 4 的件能放入高 5 或高 8 的旧层，BHF 偏向高 5 的层；最新层必要时还可以增高。";
            case "BAF" -> "两个可行旧层的层尾分别是 4×6 和 3×10，分数为 24 与 30，BAF 选前者；这些是层尾区域，不是矮件头顶的小洞。";
            case "WWF" -> "两个候选放入后分别剩宽 3 和 8，通常选剩 8 的层；若另有一个恰好填满层尾的候选，则按本实现的完全匹配规则优先处理。";
            default -> throw new IllegalArgumentException(key);
        };
        String mode = global
                ? "GLOBAL（全局取件）会在每一步查看所有尚未处理的零件，按各自选层评分比较“零件＋层”的组合再决定先放谁；评分并列时按层序与已有零件顺序处理。不是仅在开始时排序一次。对于 NF，候选仍只来自最新层。"
                : "SEQUENTIAL（顺序取件）先按所选排序得到队列，再逐个处理零件；为当前件按选层规则找位置，只有无法放入已有候选层时才尝试新层。";
        String waste = wm
                ? "每个零件会先尝试 WM（Waste Map，空洞回收表）。一层关闭时，把矮件上方的矩形空洞加入回收表，后续小件可脱离层尾规则填入；没有合适空洞才执行普通选层流程。"
                : "此配置不维护 WM 空洞回收表。回看旧层时只会继续使用层尾宽度，不会自动把零件放到矮件上方。";
        return new Guide(
                "Shelf（层架法）把板材想成从下往上叠的书架，每层从左往右摆矩形。" + rule,
                mode + " 最新层可在板材边界内增高，已关闭层的高度固定。" + waste,
                example + (wm ? "例如一个高 4 的层中，有件只高 2、宽 3，关闭层后，其上方 3×2 的空洞可交给 WM 回收；这与层尾剩余空间是两回事。" : ""),
                "适合快速建立容易解释的排样基线。" + (global ? "此配置用于观察同时选择取件与层位置的影响。" : "固定取件顺序便于观察选层规则本身的影响。")
                        + (wm ? "可用于检查后续小件能否利用已记录的层内空洞。" : "也可与相同规则的 WM 配置对照。"),
                "层边界限制空间利用，早期选层会影响后续零件；面积、宽度或高度评分都不保证最终最优。"
                        + (global ? "GLOBAL 每步检查更多候选，可能改变顺序并增加成本，也不保证优于顺序取件。" : "效果会受输入顺序影响。")
                        + (wm ? "WM 增加空闲区分割与维护成本，且仅回收已记录的矩形空洞。"
                        + (AlgorithmCatalog.compatibilityOnly(id) ? "此项为兼容配置：当前十二组面积降序实验未观察到它相对基础规则的利用率提升，但不能据此断言对所有输入无效。" : "有可容纳后续零件的空洞时才可能受益。") : ""));
    }

    private static Guide skyline(AlgorithmId id) {
        boolean wm = id.name().endsWith("_WM");
        boolean bestFit = id == AlgorithmId.SKYLINE_BF || id == AlgorithmId.SKYLINE_BF_WM;
        return new Guide(
                "Skyline（天际线）用已放零件的顶部折线描述可放边界。" + (bestFit
                        ? "BF（Best-Fit，最佳匹配）在本实现中优先减少新件底边跨越低轮廓时遮住的空白面积，再比较顶部高度与横坐标。"
                        : "BL（Bottom-Left，左下评分）在本实现中优先选择放置后顶部最低的位置，再比较横坐标。"),
                (wm ? "按预定队列逐个取件，先找 WM（空洞回收表）中的可用矩形区域；无法回填时才比较天际线候选。更新轮廓时把其下新形成的可回收空洞加入 WM。"
                        : "采用 GLOBAL 全局取件：每一步同时比较剩余零件、可用方向与轮廓位置，再用对应评分选一个组合。更新轮廓后继续比较。此项没有 WM。"),
                (bestFit ? "若两个候选都能放下当前件，一个遮住 12 平方单位的低洼空白，另一个只遮住 3，会先考虑后者。这里比较的是空白损失，不是接触边长。"
                        : "若一个候选的底部高 2、件高 6，顶部为 8；另一个底部高 4、件高 3，顶部为 7，本规则优先考虑顶部为 7 的候选。")
                        + (wm ? "已记录的轮廓下方小洞还可以交给后续小件填入。" : "被轮廓遮住的空洞不会再通过本配置回填。"),
                "适合研究轮廓放置规则的取舍。" + (wm ? "大小件互补且存在可回收空洞时，可检验回填价值。" : "可用于观察全局选择零件与位置对构造结果的影响。"),
                "评分只决定当前候选的偏好，不保证整批零件最优。"
                        + (wm ? "WM 需要维护碎片区域；碎片不能容纳后续件时可能没有收益。"
                        : "没有空洞回收，轮廓下仍可用的区域可能被忽略。")
                        + "现有 GLOBAL 入口与顺序 WM 入口同时改变了取件方式，直接比较不能把差异全部归因于 WM；应使用固定取件模式的 WM 单变量对照。");
    }

    private static Guide maxRects(AlgorithmId id) {
        String rule = switch (id) {
            case MAXRECTS_BSSF -> "BSSF（Best Short Side Fit，短边匹配）把宽、高两个剩余量中较小的那个作为首要分数，越小越好，并用较大的剩余量处理并列。";
            case MAXRECTS_BLSF -> "BLSF（Best Long Side Fit，长边匹配）把宽、高两个剩余量中较大的那个作为首要分数，越小越好，再比较较小的剩余量。";
            case MAXRECTS_BAF -> "BAF（Best Area Fit，面积匹配）先比较空闲矩形面积减零件面积的差，越小越好，再用边长剩余量处理并列。";
            case MAXRECTS_BL -> "BL（Bottom-Left，左下位置）先比较放置后的顶部高度，再比较横坐标，偏向从低处、左侧生长布局。";
            case MAXRECTS_CP -> "CP（Contact Point，接触周长）计算零件与板材边界、已有零件贴合的边长，优先选接触总长度较大的位置。";
            default -> throw new IllegalArgumentException(id.name());
        };
        String example = switch (id) {
            case MAXRECTS_BSSF -> "把 3×2 的件放入 4×7 空闲区，两个剩余量是 1 和 5，首要分数是 1；放进 6×6 时分数是 3，前者更优先。";
            case MAXRECTS_BLSF -> "同样是 3×2 的件，放进 4×7 的最大剩余量是 5，放进 6×6 是 4，因此 BLSF 倾向后者；它与 BSSF 可以作出不同选择。";
            case MAXRECTS_BAF -> "3×2 的件面积为 6，放进面积 12 或 20 的空闲矩形，面积差分别是 6 和 14，会优先考虑前者。";
            case MAXRECTS_BL -> "一个可行位置放完顶部高 8，另一个顶部高 5，会优先考虑后者；同样高时再向左靠。";
            case MAXRECTS_CP -> "一个候选只与板材接触长 3 的一条边，另一个还能紧贴已有件，使总接触达到 7，会优先考虑接触更多的候选。";
            default -> throw new IllegalArgumentException(id.name());
        };
        return new Guide(
                "MaxRects（最大空闲矩形）用多个尽可能大的空白矩形描述剩余空间，空白矩形之间允许重叠。" + rule,
                "该独立构造入口每一步比较尚未放置零件、允许方向与空闲区的候选，按当前规则择优；放入后切分所有与新件相交的空闲矩形，并删掉被其他空闲矩形包含的冗余项。",
                example + "空闲区重叠只是同一空间的多种表示，不允许最终零件重叠；独立验证器会检查实际布局。",
                "适合不规则剩余空间较多的排样。可在同一实例、旋转权限、取件方式下对比五种评分，理解“边长、面积、位置、接触”各自偏好。",
                "空闲矩形列表可能增长，切分、包含判断与候选比较会增加成本；一次贪心评分看不到后续全部影响。它只是 MaxRects 的一种规则；BEST 会分别跑五个规则，耗费更多评价后择优。");
    }

    private static Guide tabu(AlgorithmId id) {
        String memory = switch (id) {
            case TABU_FULL -> "Full（完整状态）保存最近接受过的整个排列，再次遇到相同排列时拒绝，像给走过的完整路线作标记。";
            case TABU_MOVE -> "Move（交换操作）记住最近交换过的零件对，暂时禁止同一对再次交换，减少立即反向走回原路。";
            case TABU_POSITION -> "Position（位置属性）记住零件离开的序列位置，暂时禁止它回到原来的位置；序列位置是第几件先排，不是板材坐标。";
            case TABU_ORDER -> "Order（相对先后）记住一次改动打破的先后关系，暂时禁止恢复这些关系，不要求零件相邻。";
            case TABU_ADJACENCY -> "Adjacency（有向相邻关系）记住刚被打破的相邻零件对，暂时禁止恢复这段邻接，关注队列里的局部结构。";
            case TABU_PLACEMENT -> "Placement（放置属性）把排列解码成实际布局，记住改动前被改变的零件放置属性，暂时禁止恢复这些属性。";
            default -> throw new IllegalArgumentException(id.name());
        };
        String example = switch (id) {
            case TABU_FULL -> "刚离开 A-B-C 这个排列，又通过另一条操作回到 A-B-C，完整状态记忆可以识别重复；只要排列不同，并不会自动认为它重复。";
            case TABU_MOVE -> "交换了零件 A、B 后，即使它们的位置又有所变化，记忆到期前再交换这对零件仍可能被禁止。";
            case TABU_POSITION -> "A 刚离开队列第 3 位，短期内即使换不同的搭档，也不能轻易把 A 放回第 3 位。";
            case TABU_ORDER -> "旧排列中 A 在 B 前，改动后 B 在 A 前，原来的 A 在 B 前关系暂时受限，避免立刻恢复原结构。";
            case TABU_ADJACENCY -> "原来 A 后面紧接 B，改动后它们分开；短期内重新出现有向邻接 A→B 的排列可能被禁。不是把所有新形成的邻接都禁止。";
            case TABU_PLACEMENT -> "某件刚从左下区域移到了别处，记忆会限制它立即恢复旧放置属性。实际比较的是定义好的属性，而不是凭视觉判断两张图是否相似。";
            default -> throw new IllegalArgumentException(id.name());
        };
        return new Guide(
                "禁忌搜索（Tabu Search）通过短期记忆减少在相似方案之间反复来回。一个状态是零件的处理排列，解码器负责把它变成二维坐标。" + memory,
                "从当前排列检查交换邻居，调用解码器评价，选择允许的候选继续前进并更新记忆。允许某些暂时变差的移动以离开局部最优，同时保存历史最好方案。"
                        + (id == AlgorithmId.TABU_FULL ? "本实现对已记住的完整排列直接拒绝。" : "若禁忌候选能刷新历史最好面积，可通过“特赦”破例接受。"),
                example,
                "适合在同一解码器、预算与种子条件下研究“记住什么”对搜索的影响；这些入口共享搜索框架，属于同一家族的记忆配置。",
                "记忆过短可能循环，过长可能阻挡有价值的尝试；每个邻居都可能需要解码。"
                        + (id == AlgorithmId.TABU_FULL ? "保存完整排列还需要额外存储与状态比较。"
                        : id == AlgorithmId.TABU_PLACEMENT ? "放置属性需要生成布局并提取特征，通常比只看排列属性更贵。"
                        : "属性相同并不意味着完整排列或几何布局相同，简化记忆会影响哪些方向被限制。")
                        + "结果依赖实例和预算，记忆更复杂并不自动更好。");
    }

    private static Guide genetic(AlgorithmId id) {
        boolean adaptive = id == AlgorithmId.ADAPTIVE_GA;
        return new Guide(
                "遗传算法（GA）同时保留一群候选排列，像同时尝试多条路线；一个排列叫个体，装入面积叫适应度。" + (adaptive
                        ? "自适应配置根据个体相对种群适应度调整交叉、变异概率。" : "普通 GA 使用配置中给定的交叉、变异概率，作为固定概率基线。"),
                "先构造并评价种群，让较好个体有机会留下后代。交叉把两个父代的排列信息组合，变异对排列作随机改动；保留优秀个体，再重复评价与繁殖。"
                        + (adaptive ? "本实现让相对较差个体获得更强探索、较好个体减少扰动，概率受上下界限制；不是自动寻找最优参数。" : "概率不会因为某个个体比种群更好而自动改变，便于与自适应配置对照。"),
                "两个父代分别保留了有利的零件先后关系，合法排列交叉尝试让后代继承部分关系；随机交换又可能创造父代没有的新顺序。"
                        + (adaptive ? "较差个体可以用更强的变异寻找新区域，而较好个体尽量保护已有结构。" : "固定变异概率决定这类探索发生的频率。"),
                "适合搜索空间大、希望同时探索多种排列的场景。固定种子并比较多个独立运行，才能判断平均质量与波动。",
                "每一代要评价多个个体，种群越大通常成本越高；个体过于相似时可能早熟收敛。"
                        + (adaptive ? "自适应仍需要选择概率上下界，不保证每个实例都优于固定概率 GA。" : "固定概率可能难以兼顾早期探索与后期保留，需要结合预算选择。"));
    }

    private static Guide hybrid(AlgorithmId id) {
        boolean sa = id == AlgorithmId.GA_SA;
        return new Guide(
                "遗传混合搜索在 GA 的种群探索中加入局部强化，也称模因算法：外层寻找不同排列，内层继续打磨部分候选。此配置使用" + (sa ? "模拟退火（SA）" : "禁忌搜索（Tabu）") + "进行强化。",
                "先通过选择、交叉与变异产生候选，再根据混合配置为部分个体分配局部搜索预算。内层使用同一解码器评价改动，把改进结果反馈给外层；局部搜索也计入总评价预算。"
                        + (sa ? "模拟退火用温度控制偶尔接受退步的概率。" : "禁忌局部搜索用短期交换记忆减少马上回头。"),
                "GA 找到利用率 90% 的排列后，局部强化可能进一步找到 92%，改进后的个体继续参与后续搜索；如果内层没有改进，就不能把额外计算自动当成收益。",
                "适合研究全局探索与局部打磨能否互补，以及在给定预算下怎样分配二者的工作量。",
                "局部强化会消耗本可用于探索更多个体的预算，也可能让种群变得相似。与普通 GA 比较时必须统一解码器、总预算和种子；GA+SA 与 GA+Tabu 都有真实机制差异，但不能仅凭名字判断谁更强。");
    }
